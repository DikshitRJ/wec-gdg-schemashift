"""PostgreSQL DDL script generator.

Spec: scriptgen/ddl
"""

from __future__ import annotations

from pathlib import Path
from schemashift.contracts.schema_map import Column, ForeignKey, Index, SchemaMap, Table
from schemashift.gen.header import make_sql_header
from schemashift.identifiers import quote_ident
from schemashift.migrate.ordering import get_table_topological_order


def generate_ddl_sql(schema_map: SchemaMap) -> str:
    """Render PostgreSQL DDL from a frozen SchemaMap in topological order."""
    tables = get_table_topological_order(schema_map)
    lines: list[str] = [make_sql_header(schema_map.map_hash, schema_map.map_version, "ddl")]

    indexes_to_create: list[tuple[str, Index]] = []

    for table in tables:
        tbl_q = quote_ident(table.name)
        lines.append(f"CREATE TABLE IF NOT EXISTS {tbl_q} (")
        col_defs: list[str] = []

        # Columns
        for col in table.columns:
            c_name = quote_ident(col.name)
            col_type = col.pg_type

            parts = [f"  {c_name} {col_type}"]
            if col.identity:
                parts.append("GENERATED BY DEFAULT AS IDENTITY")
            if not col.nullable:
                parts.append("NOT NULL")
            if col.default:
                parts.append(f"DEFAULT {col.default}")

            col_defs.append(" ".join(parts))

        # Primary Key
        if table.primary_key:
            pk_cols = ", ".join(quote_ident(c) for c in table.primary_key)
            col_defs.append(f"  CONSTRAINT {quote_ident(f'pk_{table.name}')} PRIMARY KEY ({pk_cols})")

        # Foreign Keys
        for fk in table.foreign_keys:
            cols = ", ".join(quote_ident(c) for c in fk.columns)
            ref_cols = ", ".join(quote_ident(c) for c in fk.ref_columns)
            fk_name = f"fk_{table.name}_{'_'.join(fk.columns)}"
            fk_clause = f"  CONSTRAINT {quote_ident(fk_name)} FOREIGN KEY ({cols}) REFERENCES {quote_ident(fk.ref_table)} ({ref_cols})"
            if fk.on_delete and fk.on_delete.upper() != "NO ACTION":
                fk_clause += f" ON DELETE {fk.on_delete.upper()}"
            col_defs.append(fk_clause)

        # Check constraint for child table position column
        if any(c.name == "position" for c in table.columns):
            col_defs.append(f"  CONSTRAINT {quote_ident(f'chk_{table.name}_pos')} CHECK ({quote_ident('position')} >= 0)")

        lines.append(",\n".join(col_defs))
        lines.append(");\n")

        # Collect indexes
        for idx in table.indexes:
            indexes_to_create.append((table.name, idx))

    # Add indexes after table definitions
    for tbl_name, idx in indexes_to_create:
        u = "UNIQUE " if idx.unique else ""
        idx_name = f"idx_{tbl_name}_{'_'.join(idx.columns)}"
        cols_q = ", ".join(quote_ident(c) for c in idx.columns)
        lines.append(
            f"CREATE {u}INDEX IF NOT EXISTS {quote_ident(idx_name)} ON {quote_ident(tbl_name)} ({cols_q});"
        )

    lines.append("")
    return "\n".join(lines)


def write_ddl(schema_map: SchemaMap, out_path: str | Path) -> str:
    """Generate and write DDL SQL file."""
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    sql = generate_ddl_sql(schema_map)
    p.write_text(sql, encoding="utf-8")
    return str(p.resolve())
